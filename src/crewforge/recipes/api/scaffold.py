"""Write a runnable FastAPI project from a pipeline result."""

from __future__ import annotations

import json
from pathlib import Path

from .generator import CodeGenerator
from .pipeline import PipelineResult


class ProjectScaffold:
    def __init__(self, output_dir: str | Path) -> None:
        self.output_dir = Path(output_dir)
        self.generator = CodeGenerator()

    def scaffold(self, result: PipelineResult) -> dict[str, Path]:
        files: dict[str, Path] = {}
        self.output_dir.mkdir(parents=True, exist_ok=True)
        files["routes"] = self._write("routes.py", result.router_code)
        files["models"] = self._write("models.py", result.model_code)
        files["auth"] = self._write("auth.py", result.auth_code)
        files["tests"] = self._write("tests/test_api.py", result.test_code)
        files["openapi"] = self._write("openapi.json", json.dumps(result.openapi_spec, indent=2))
        files["docs"] = self._write("API.md", result.docs)
        files["main"] = self._write("main.py", self._main(result))
        files["requirements"] = self._write(
            "requirements.txt", self.generator.render("requirements.j2", {})
        )
        files["dockerfile"] = self._write("Dockerfile", self.generator.render("dockerfile.j2", {}))
        files["env"] = self._write(".env.example", self.generator.render("env.example.j2", {}))
        files["conftest"] = self._write("tests/conftest.py", self._conftest())
        return files

    def _write(self, name: str, content: str) -> Path:
        path = self.output_dir / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        return path

    def _main(self, result: PipelineResult) -> str:
        d = result.description
        # repr() keeps model-written titles from breaking out of the string literal.
        return (
            f'"""{d.title.replace(chr(34) * 3, "")} -- generated by crewforge."""\n'
            "from fastapi import FastAPI\n\n"
            "from routes import router\n\n"
            f"app = FastAPI(title={d.title!r}, description={d.description!r}, "
            f"version={d.version!r})\n"
            "app.include_router(router)\n\n\n"
            '@app.get("/health")\n'
            "async def health():\n"
            '    return {"status": "ok"}\n'
        )

    def _conftest(self) -> str:
        return (
            '"""Test configuration."""\n'
            "import sys\n"
            "from pathlib import Path\n\n"
            "import pytest\n"
            "from fastapi.testclient import TestClient\n\n"
            "sys.path.insert(0, str(Path(__file__).resolve().parents[1]))\n\n\n"
            "@pytest.fixture\n"
            "def client():\n"
            "    from main import app\n\n"
            "    return TestClient(app)\n"
        )
